const DICTIONARIES: Record<Lang, Dictionary> = { en, es }

export function dictionary(lang: Lang): Dictionary {
	return DICTIONARIES[lang] ?? en
}

/** The texts in the language of this page (chosen by the root loader). */
export function useT(): Dictionary {
	const data = useRouteLoaderData('root') as { lang?: Lang } | undefined
	return dictionary(data?.lang ?? 'en')
}

export function useLang(): Lang {
	const data = useRouteLoaderData('root') as { lang?: Lang } | undefined
	return data?.lang ?? 'en'
}

/** A length of time, rounded the way people say it: hours, days, weeks or months. */
export function duration(t: Dictionary, hours: number) {
	if (hours < 48) return t.units.hours(Math.max(0, Math.round(hours)))
	const days = hours / 24
	if (days < 14) return t.units.days(Math.round(days))
	if (days < 60) return t.units.weeks(Math.round(days / 7))
	return t.units.months(Math.round(days / 30))
}
